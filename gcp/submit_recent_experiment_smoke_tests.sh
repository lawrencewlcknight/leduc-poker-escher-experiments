#!/usr/bin/env bash
set -euo pipefail

# Submit one Google Batch job that runs smoke tests for ESCHER Experiments
# 23-27. Required environment is the same as submit_batch_experiment.sh:
# PROJECT_ID, REGION, BUCKET, and SA_EMAIL.
#
# Optional environment overrides:
#   MACHINE_TYPE, MAX_RUN_SECONDS, CPU_MILLI, MEMORY_MIB, BOOT_DISK_SIZE_GB,
#   JOB_TIMESTAMP, SMOKE_OUTPUT_ROOT, SMOKE_SEED, SMOKE_ITERATIONS,
#   SMOKE_TRAVERSALS, SMOKE_VALUE_TRAVERSALS, SMOKE_EVALUATION_INTERVAL,
#   SMOKE_POLICY_TRAIN_STEPS, SMOKE_REGRET_TRAIN_STEPS,
#   SMOKE_VALUE_TRAIN_STEPS, SMOKE_BATCH_SIZE, SMOKE_MEMORY_CAPACITY
#
# Usage:
#   ./gcp/submit_recent_experiment_smoke_tests.sh [JOB_NAME]

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
JOB_TIMESTAMP="${JOB_TIMESTAMP:-$(date +%Y%m%d-%H%M%S)}"
JOB_NAME="${1:-escher-smoke-exp23-27-${JOB_TIMESTAMP}}"

MACHINE_TYPE="${MACHINE_TYPE:-n2-standard-4}"
MAX_RUN_SECONDS="${MAX_RUN_SECONDS:-3600}"
CPU_MILLI="${CPU_MILLI:-4000}"
MEMORY_MIB="${MEMORY_MIB:-16000}"
BOOT_DISK_SIZE_GB="${BOOT_DISK_SIZE_GB:-100}"

SMOKE_OUTPUT_ROOT="${SMOKE_OUTPUT_ROOT:-outputs/cloud/${JOB_NAME}}"
SMOKE_SEED="${SMOKE_SEED:-1234}"
SMOKE_ITERATIONS="${SMOKE_ITERATIONS:-2}"
SMOKE_TRAVERSALS="${SMOKE_TRAVERSALS:-2}"
SMOKE_VALUE_TRAVERSALS="${SMOKE_VALUE_TRAVERSALS:-2}"
SMOKE_EVALUATION_INTERVAL="${SMOKE_EVALUATION_INTERVAL:-1}"
SMOKE_POLICY_TRAIN_STEPS="${SMOKE_POLICY_TRAIN_STEPS:-1}"
SMOKE_REGRET_TRAIN_STEPS="${SMOKE_REGRET_TRAIN_STEPS:-1}"
SMOKE_VALUE_TRAIN_STEPS="${SMOKE_VALUE_TRAIN_STEPS:-1}"
SMOKE_BATCH_SIZE="${SMOKE_BATCH_SIZE:-2}"
SMOKE_MEMORY_CAPACITY="${SMOKE_MEMORY_CAPACITY:-128}"

EXPERIMENT_COMMAND="SMOKE_OUTPUT_ROOT=${SMOKE_OUTPUT_ROOT} SMOKE_SEED=${SMOKE_SEED} SMOKE_ITERATIONS=${SMOKE_ITERATIONS} SMOKE_TRAVERSALS=${SMOKE_TRAVERSALS} SMOKE_VALUE_TRAVERSALS=${SMOKE_VALUE_TRAVERSALS} SMOKE_EVALUATION_INTERVAL=${SMOKE_EVALUATION_INTERVAL} SMOKE_POLICY_TRAIN_STEPS=${SMOKE_POLICY_TRAIN_STEPS} SMOKE_REGRET_TRAIN_STEPS=${SMOKE_REGRET_TRAIN_STEPS} SMOKE_VALUE_TRAIN_STEPS=${SMOKE_VALUE_TRAIN_STEPS} SMOKE_BATCH_SIZE=${SMOKE_BATCH_SIZE} SMOKE_MEMORY_CAPACITY=${SMOKE_MEMORY_CAPACITY} bash gcp/run_recent_experiment_smoke_tests.sh"

"${SCRIPT_DIR}/submit_batch_experiment.sh" \
  "${JOB_NAME}" \
  "${EXPERIMENT_COMMAND}" \
  "${MACHINE_TYPE}" \
  "${MAX_RUN_SECONDS}" \
  "${CPU_MILLI}" \
  "${MEMORY_MIB}" \
  "${BOOT_DISK_SIZE_GB}"
